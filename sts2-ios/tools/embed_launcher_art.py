#!/usr/bin/env python3
"""Embed launcher/art/launcher-home.jpg into launcher/STS2LauncherArt.mm.

The generated Xcode project has no resource build phase we control, so the
artwork is compiled in as a byte array. Re-run after replacing the JPEG:
    python3 sts2-ios/tools/embed_launcher_art.py
"""
from pathlib import Path

LAUNCHER = Path(__file__).resolve().parent.parent / "ios-export" / "launcher"
data = (LAUNCHER / "art" / "launcher-home.jpg").read_bytes()
lines = []
for i in range(0, len(data), 24):
    lines.append("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
source = (
    "// Generated by tools/embed_launcher_art.py from art/launcher-home.jpg. Do not edit.\n"
    '#import "STS2LauncherArt.h"\n'
    f"static const unsigned char kLauncherArt[{len(data)}] = {{\n" + "\n".join(lines) + "\n};\n"
    "UIImage *STS2LauncherArtImage(void) {\n"
    "    static UIImage *image;\n"
    "    static dispatch_once_t once;\n"
    f"    dispatch_once(&once, ^{{ image = [UIImage imageWithData:[NSData dataWithBytesNoCopy:(void *)kLauncherArt length:{len(data)} freeWhenDone:NO]]; }});\n"
    "    return image;\n"
    "}\n"
)
(LAUNCHER / "STS2LauncherArt.mm").write_text(source)
(LAUNCHER / "STS2LauncherArt.h").write_text(
    "#import <UIKit/UIKit.h>\n"
    "/// 1536x1024 launcher artwork (night cabin). Menu labels are painted into the picture.\n"
    "FOUNDATION_EXPORT UIImage * _Nullable STS2LauncherArtImage(void);\n"
)
print("embedded", len(data), "bytes")
