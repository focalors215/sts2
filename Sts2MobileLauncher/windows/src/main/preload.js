'use strict';

const { contextBridge, ipcRenderer } = require('electron');

const call = (channel, ...args) => ipcRenderer.invoke(channel, ...args).then(result => {
	if (!result.ok) {
		throw new Error(result.error);
	}
	return result.value;
});

contextBridge.exposeInMainWorld('launcher', {
	state: () => call('state'),
	setLastTab: tab => call('ui:lastTab', tab),
	setWelcomeDone: () => call('ui:welcomeDone'),
	updateSettings: patch => call('settings:update', patch),
	detectSteam: () => call('profiles:detect'),
	addFolder: () => call('profiles:addFolder'),
	selectProfile: id => call('profiles:select', id),
	updateProfile: (id, patch) => call('profiles:update', id, patch),
	removeProfile: id => call('profiles:remove', id),
	pickSaveRoot: () => call('saves:pickRoot'),
	createSnapshot: () => call('saves:snapshot'),
	restoreSnapshot: name => call('saves:restore', name),
	deleteSnapshot: name => call('saves:deleteSnapshot', name),
	setModsMaster: enabled => call('mods:setMaster', enabled),
	setModEnabled: (id, enabled) => call('mods:setEnabled', id, enabled),
	fixModOrder: () => call('mods:fixOrder'),
	deleteMod: (id, relativePath) => call('mods:delete', id, relativePath),
	prepareModImport: kind => call('mods:prepareImport', kind),
	commitModImport: token => call('mods:commitImport', token),
	cancelModImport: token => call('mods:cancelImport', token),
	open: (target, profileId) => call('shell:open', target, profileId),
	openExternal: url => call('shell:external', url),
	launch: () => call('game:launch'),
	onlineSetNickname: nickname => call('online:setNickname', nickname),
	onlineSetFrpToken: token => call('online:setFrpToken', token),
	onlineScan: () => call('online:scan'),
	onlineCreate: () => call('online:create'),
	onlineJoin: (host, port) => call('online:join', host, port),
	onlineHostLan: () => call('online:hostLan'),
	onlineJoinLan: (host, port) => call('online:joinLan', host, port),
	onlineStop: () => call('online:stop'),
	listLogs: () => call('logs:list'),
	readLog: id => call('logs:read', id),
	exportLogs: () => call('logs:export'),
	writeLog: (level, tag, message, stack) => call('logs:write', level, tag, message, stack),
	ackCrashes: names => call('crash:ack', names),
	aiGetConfig: () => call('ai:getConfig'),
	aiSaveConfig: patch => call('ai:saveConfig', patch),
	aiStart: ids => call('ai:start', ids),
	aiAsk: question => call('ai:ask', question),
	aiStop: () => call('ai:stop'),
	workshopBrowse: options => call('workshop:browse', options),
	workshopItem: ref => call('workshop:item', ref),
	workshopLocal: () => call('workshop:local'),
	workshopSubscribe: id => call('workshop:subscribe', id),
	workshopPrepareInstall: id => call('workshop:prepareInstall', id),
	workshopCommitInstall: token => call('workshop:commitInstall', token),
	workshopCancelInstall: token => call('workshop:cancelInstall', token),
	workshopCheckUpdates: () => call('workshop:checkUpdates'),
	workshopForget: (id, deleteFiles) => call('workshop:forget', id, deleteFiles),
	onWorkshopProgress: callback => ipcRenderer.on('workshop-progress', (event, info) => callback(info)),
	cloudGetConfig: () => call('cloud:getConfig'),
	cloudSaveConfig: patch => call('cloud:saveConfig', patch),
	cloudClear: () => call('cloud:clear'),
	cloudTest: () => call('cloud:test'),
	cloudRefresh: () => call('cloud:refresh'),
	cloudPull: force => call('cloud:pull', force),
	cloudPush: force => call('cloud:push', force),
	onCloudProgress: callback => ipcRenderer.on('cloud-progress', (event, info) => callback(info)),
	onCloudAuto: callback => ipcRenderer.on('cloud-auto', (event, info) => callback(info)),
	nexusGetConfig: () => call('nexus:getConfig'),
	nexusSaveKey: key => call('nexus:saveKey', key),
	nexusClearKey: () => call('nexus:clearKey'),
	nexusDiscover: () => call('nexus:discover'),
	nexusSearch: query => call('nexus:search', query),
	nexusMod: modId => call('nexus:mod', modId),
	nexusPrepareInstall: (modId, fileId, nxm) => call('nexus:prepareInstall', modId, fileId, nxm),
	nexusCommitInstall: token => call('nexus:commitInstall', token),
	nexusCancelInstall: token => call('nexus:cancelInstall', token),
	onNexusProgress: callback => ipcRenderer.on('nexus-progress', (event, info) => callback(info)),
	checkUpdate: () => call('update:check'),
	updateSettings2: patch => call('update:settings', patch),
	backupMeasure: () => call('backup:measure'),
	backupExport: includeMods => call('backup:export', includeMods),
	backupImport: () => call('backup:import'),
	filesRoots: () => call('files:roots'),
	filesList: (root, relative) => call('files:list', root, relative),
	filesRead: (root, relative) => call('files:read', root, relative),
	filesWrite: (root, relative, text, mtimeMs) => call('files:write', root, relative, text, mtimeMs),
	filesReveal: (root, relative) => call('files:reveal', root, relative),
	onUpdateAvailable: callback => ipcRenderer.on('update-available', (event, info) => callback(info)),
	onAiProgress: callback => ipcRenderer.on('ai-progress', (event, summary) => callback(summary)),
	onGameExited: callback => ipcRenderer.on('game-exited', (event, info) => callback(info)),
	onOnlineChanged: callback => ipcRenderer.on('online-changed', () => callback()),
});
